/**
 * Regenerates src/data/seedExercises.ts from free-exercise-db (public domain).
 *
 * Run by hand — `npm run exercises` — and the result is committed. Fetching at
 * build time would put a network call inside the Pages deploy that can fail or
 * silently drift; a vendored file makes the build hermetic and the diff
 * reviewable.
 *
 * The source is ~1 MB, most of it prose instructions and image paths we have no
 * use for. Only the five fields the picker actually reads survive.
 */

import { writeFile } from 'node:fs/promises';

const SOURCE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';
const OUT = new URL('../src/data/seedExercises.ts', import.meta.url);

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE} responded ${res.status}`);
const all = await res.json();

const kept = all
  // Cardio is tracked in a different app by an explicit spec decision, so it
  // would only ever be noise in the picker.
  .filter((e) => e.category !== 'cardio')
  .map((e) => ({
    name: e.name,
    equipment: e.equipment ?? '',
    force: e.force ?? '',
    category: e.category,
    primaryMuscles: e.primaryMuscles ?? [],
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const body = `/**
 * Generated by scripts/fetch-exercises.mjs — do not edit by hand.
 *
 * Source: free-exercise-db (https://github.com/yuhonas/free-exercise-db),
 * public domain. ${kept.length} entries; cardio excluded.
 *
 * Imported dynamically so this never lands in the chunk you wait on at the gym.
 */

import type { SeedExercise } from '../lib/seedLibrary';

export const SEED_EXERCISES: SeedExercise[] = ${JSON.stringify(kept, null, 0)};
`;

await writeFile(OUT, body, 'utf8');
console.log(`Wrote ${kept.length} exercises (${(body.length / 1024).toFixed(0)} kB)`);
